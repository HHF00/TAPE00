export function isKnownEtfSymbol(symbol: string): boolean {
  const clean = symbol.trim().toUpperCase();
  const meta = US_TICKER_DIRECTORY[clean];
  if (!meta) return false;
  return Boolean(meta.isETF) || meta.sector.toLowerCase().includes('etf');
}

export function isKnownIndexSymbol(symbol: string): boolean {
  const clean = symbol.trim().toUpperCase();
  if (clean.startsWith('^') || clean.startsWith('MYIDX:')) return true;
  const meta = US_TICKER_DIRECTORY[clean];
  return Boolean(meta?.isIndex);
}

